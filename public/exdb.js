// Resolve an item to its concrete exercise for a phase index (0–2).
export function resolve(item, phase) {
  const key = Array.isArray(item) ? item[Math.min(phase, item.length - 1)] : item;
  const e = EXDB[key];
  if (!e) return null;
  return { key, ...e, setsNow: e.sets[Math.min(phase, e.sets.length - 1)] };
}

